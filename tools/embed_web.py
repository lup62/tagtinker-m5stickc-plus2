#!/usr/bin/env python3
"""Generate src/web_assets.h from the HTML in web/.

  panel.html            -> PANEL_HTML   (main control panel)
  prep_src.html +        -> PREP_HTML   (Image Prep tool + M5 "Send to M5" panel)
    m5_inject.html

Each asset is emitted as a PROGMEM char array of raw bytes, so there is no
C string-literal length limit to worry about and the HTML needs no escaping.
"""
import os

try:
    Import  # noqa: F821  (PlatformIO injects this)
    env = DefaultEnvironment()  # noqa: F821
    PROJECT_DIR = env["PROJECT_DIR"]
except Exception:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(PROJECT_DIR, "web")
OUT = os.path.join(PROJECT_DIR, "src", "web_assets.h")


def read(name):
    with open(os.path.join(WEB, name), "rb") as f:
        return f.read()


def emit_array(name, data):
    # NUL-terminated so it can also be used as a C string when short enough.
    body = ",".join(str(b) for b in data)
    return (
        f"static const char {name}[] PROGMEM = {{{body},0}};\n"
        f"static const size_t {name}_LEN = {len(data)};\n"
    )


def build():
    panel = read("panel.html")

    prep = read("prep_src.html").decode("utf-8", "replace")
    inject = read("m5_inject.html").decode("utf-8", "replace")
    marker = "</body>"
    idx = prep.rfind(marker)
    if idx == -1:
        prep = prep + inject
    else:
        prep = prep[:idx] + inject + "\n" + prep[idx:]
    prep = prep.encode("utf-8")

    out = [
        "/* Auto-generated by tools/embed_web.py — do not edit. */\n",
        "#pragma once\n#include <Arduino.h>\n\n",
        emit_array("PANEL_HTML", panel),
        "\n",
        emit_array("PREP_HTML", prep),
    ]
    text = "".join(out)

    # Only rewrite when changed, so PlatformIO doesn't rebuild needlessly.
    old = ""
    if os.path.exists(OUT):
        with open(OUT) as f:
            old = f.read()
    if old != text:
        with open(OUT, "w") as f:
            f.write(text)
        print("embed_web.py: wrote %s (panel %d B, prep %d B)" % (OUT, len(panel), len(prep)))
    else:
        print("embed_web.py: web_assets.h up to date")


build()
